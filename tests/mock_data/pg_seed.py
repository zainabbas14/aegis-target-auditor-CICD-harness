"""Export the seeded SQLite ledger as a deterministic Postgres seed script.

The SQLite build stays the single generator. This module only translates its
rows into INSERT statements, which docker-entrypoint-initdb.d runs on first
start. The output is plain text, committed, and diff-reviewable - a change to
the fixtures shows up in code review as a readable SQL diff.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

# Parent tables first (FK order). Each with a deterministic ORDER BY.
_TABLES: tuple[tuple[str, str], ...] = (
    ("vendors", "vendor_id"),
    ("contracts", "contract_ref"),
    ("contract_rates", "contract_ref, item_code"),
    ("purchase_orders", "po_number"),
    ("historical_payments", "payment_id"),
)


def _literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):  # bool is an int subclass; never expected here
        raise TypeError("unexpected boolean in ledger data")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    raise TypeError(f"unsupported type {type(value).__name__} in ledger data")


def export_postgres_seed(sqlite_path: Path, out_path: Path) -> Path:
    conn = sqlite3.connect(f"file:{sqlite_path.resolve()}?mode=ro", uri=True)
    lines = [
        "-- GENERATED by tests/mock_data/pg_seed.py from the SQLite build. Do not edit.",
        "BEGIN;",
    ]
    try:
        for table, order_by in _TABLES:
            cur = conn.execute(f"SELECT * FROM {table} ORDER BY {order_by}")  # noqa: S608 - constant identifiers
            columns = ", ".join(d[0] for d in cur.description)
            rows = cur.fetchall()
            lines.append(f"\n-- {table}: {len(rows)} rows")
            # Emitting SQL text from our own fixture rows; every value goes through _literal().
            lines.extend(
                f"INSERT INTO {table} ({columns}) VALUES ({', '.join(_literal(v) for v in row)});"  # noqa: S608
                for row in rows
            )
    finally:
        conn.close()
    lines += [
        "",
        "-- Explicit ids were inserted; move the identity sequence past them.",
        "SELECT setval(pg_get_serial_sequence('historical_payments', 'payment_id'),"
        " (SELECT max(payment_id) FROM historical_payments));",
        "COMMIT;",
        "",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path
