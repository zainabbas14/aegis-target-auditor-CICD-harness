-- Postgres DDL for the mock ERP. Mirrors tests/mock_data/schema.sql (SQLite);
-- test_ledger_parity.py proves both backends return identical facts.
-- Money: BIGINT minor units (cents). Never NUMERIC-as-float, never REAL.

CREATE TABLE vendors (
    vendor_id      TEXT PRIMARY KEY,
    legal_name     TEXT NOT NULL,
    tax_id         TEXT NOT NULL UNIQUE,
    remit_account  TEXT NOT NULL,
    contract_ref   TEXT,
    status         TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ON_HOLD', 'INACTIVE')),
    created_at     TIMESTAMPTZ NOT NULL
);

CREATE TABLE contracts (
    contract_ref        TEXT PRIMARY KEY,
    vendor_id           TEXT NOT NULL REFERENCES vendors (vendor_id),
    title               TEXT NOT NULL,
    effective_date      DATE NOT NULL,
    expiry_date         DATE NOT NULL CHECK (expiry_date > effective_date),
    payment_terms_days  INTEGER NOT NULL CHECK (payment_terms_days > 0),
    currency            CHAR(3) NOT NULL,
    document_path       TEXT NOT NULL
);

CREATE TABLE contract_rates (
    contract_ref          TEXT NOT NULL REFERENCES contracts (contract_ref),
    item_code             TEXT NOT NULL,
    description           TEXT NOT NULL,
    unit                  TEXT NOT NULL,
    max_unit_price_cents  BIGINT NOT NULL CHECK (max_unit_price_cents > 0),
    PRIMARY KEY (contract_ref, item_code)
);

CREATE TABLE purchase_orders (
    po_number              TEXT PRIMARY KEY,
    vendor_id              TEXT NOT NULL REFERENCES vendors (vendor_id),
    issued_on              DATE NOT NULL,
    approved_budget_cents  BIGINT NOT NULL CHECK (approved_budget_cents > 0),
    status                 TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE historical_payments (
    payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number  TEXT NOT NULL,
    vendor_id       TEXT NOT NULL REFERENCES vendors (vendor_id),
    po_number       TEXT REFERENCES purchase_orders (po_number),
    amount_cents    BIGINT NOT NULL CHECK (amount_cents > 0),
    payment_date    DATE NOT NULL,
    status          TEXT NOT NULL CHECK (status IN ('PAID', 'PENDING', 'VOID')),
    UNIQUE (vendor_id, invoice_number)
);

CREATE INDEX ix_payments_vendor_date ON historical_payments (vendor_id, payment_date);
CREATE INDEX ix_payments_vendor_amount ON historical_payments (vendor_id, amount_cents);

CREATE VIEW po_balances AS
SELECT
    po.po_number,
    po.vendor_id,
    po.approved_budget_cents,
    COALESCE(SUM(hp.amount_cents) FILTER (WHERE hp.status IN ('PAID', 'PENDING')), 0)::BIGINT AS consumed_cents,
    (po.approved_budget_cents
        - COALESCE(SUM(hp.amount_cents) FILTER (WHERE hp.status IN ('PAID', 'PENDING')), 0))::BIGINT AS remaining_cents
FROM purchase_orders po
LEFT JOIN historical_payments hp ON hp.po_number = po.po_number
GROUP BY po.po_number, po.vendor_id, po.approved_budget_cents;
